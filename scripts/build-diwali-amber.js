// Builds public/css/themes/diwali-amber.css from public/css/amber.css, so the Diwali theme stands on
// the everyday amber look (icon tiles, KPI sparklines, rank badges, the open sidebar...) instead of
// the plain pre-amber look every festival theme otherwise falls back to. Every amber rule is scoped
// :root:not([data-theme]); this copies them with that scope changed to :root[data-theme="diwali"].
// diwali.css @imports the result first, so its own maroon-and-gold rules still win.
//
// Run after any change to amber.css:   node scripts/build-diwali-amber.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'public/css/amber.css'), 'utf8');
const out = src
  .split(':root.sb-pinned:not([data-theme])').join(':root.sb-pinned[data-theme="diwali"]')
  .split(':root:not([data-theme])').join(':root[data-theme="diwali"]');
const head = '/* GENERATED by scripts/build-diwali-amber.js from public/css/amber.css — do not edit by hand;\n' +
             '   change amber.css and run the script again. The amber look, scoped to the Diwali theme. */\n';
fs.writeFileSync(path.join(root, 'public/css/themes/diwali-amber.css'), head + out);
console.log('diwali-amber.css written, ' + (out.match(/data-theme="diwali"/g) || []).length + ' scoped selectors');
